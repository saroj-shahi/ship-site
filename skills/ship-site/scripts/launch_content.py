#!/usr/bin/env python3
"""Find content that must not reach production: placeholders, scaffold leftovers,
and links that still point at the site being replaced.

Unfinished copy rarely breaks a build. "[TBD: replace before launch]", a sample
video, a "To confirm:" note on a legal page, or the create-next-app favicon all
pass lint, types, tests and Lighthouse, then ship.

Usage:
  launch_content.py [repo_dir] [--legacy-host old.example.com ...] [--json]

Kinds reported:
  placeholder  copy marked as unfinished (TBD, lorem ipsum, sample/dummy content, "to confirm")
  scaffold     create-next-app leftovers (default title, starter SVGs, default favicon)
  legacy-link  absolute URL to a --legacy-host, or a WordPress upload path (/wp-content/)
Exit 0 = clean, 1 = findings.

Scans shipped content only: app/, src/, pages/, components/, content/, data/,
messages/, locales/, public/ (text files). Tests, stories, docs and build output
are skipped, since a TODO in a README is not launch content. Every hit is a
candidate: confirm it renders before calling it a Blocker.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SCAN_DIRS = ("app", "src", "pages", "components", "content", "data", "messages", "locales", "public")
TEXT_EXT = {".ts", ".tsx", ".js", ".jsx", ".mjs", ".md", ".mdx", ".json", ".yml", ".yaml",
            ".html", ".txt", ".css", ".xml"}
SKIP_DIRS = {"node_modules", ".next", "dist", "build", "out", "coverage", ".open-next",
             "__tests__", "__mocks__", "e2e", "tests", "test", "docs"}
NON_SHIPPING = (".test.", ".spec.", ".stories.")

PLACEHOLDER = [
    (re.compile(r"lorem ipsum", re.I), "lorem ipsum"),
    (re.compile(r"\[\s*(TBD|TBC|TODO|PLACEHOLDER|INSERT)\b[^\]]*\]", re.I), "bracketed placeholder"),
    (re.compile(r"(^|[\s\"'>(:])(TBD|TBC)([\s\"'<.,:)]|$)"), "TBD/TBC"),
    (re.compile(r"replace (this )?before (launch|release|go-?live)", re.I), "replace before launch"),
    (re.compile(r"\b(sample|dummy|placeholder|filler|fake) (content|copy|text|image|video|data|testimonial|quote|logo)s?\b", re.I),
     "sample/dummy content"),
    (re.compile(r"\bto confirm\s*:", re.I), "'To confirm:' note"),
    (re.compile(r"\b(john|jane) (doe|smith)\b", re.I), "stand-in name"),
    (re.compile(r"\(?\b555\)?[-. ]?01\d\d\b"), "fictional 555 phone number"),
    (re.compile(r"[\w.+-]+@example\.(com|org|net)\b", re.I), "example.com address"),
]
# create-next-app defaults
SCAFFOLD_TEXT = [
    (re.compile(r"Create Next App"), "default create-next-app title"),
    (re.compile(r"Generated by create next app", re.I), "default create-next-app description"),
]
SCAFFOLD_FILES = ("public/next.svg", "public/vercel.svg", "public/file.svg", "public/globe.svg", "public/window.svg")
DEFAULT_FAVICON_BYTES = 25931  # size of the favicon.ico create-next-app ships
WP_UPLOAD = re.compile(r"/wp-(content|includes)/", re.I)


def shipped_files(root: Path):
    for d in SCAN_DIRS:
        base = root / d
        if not base.is_dir():
            continue
        for f in base.rglob("*"):
            rel = f.relative_to(root)
            if (f.is_file() and f.suffix.lower() in TEXT_EXT
                    and not SKIP_DIRS.intersection(rel.parts[:-1])
                    and not any(s in f.name for s in NON_SHIPPING)):
                yield f


CODE_EXT = {".ts", ".tsx", ".js", ".jsx", ".mjs", ".css"}
COMMENT = re.compile(r"^\s*(//|/\*|\*|\{/\*)")


def is_input_hint(line: str, start: int) -> bool:
    """`placeholder="Jane Doe"` (or a `ph:`/`hint:` field config) is an input hint, not page copy."""
    return bool(re.search(r"\b(placeholder|ph|hint)\s*[=:]\s*[\"'{`][^\"'}`]*$", line[:start], re.I))


def scan(root: Path, legacy_hosts: list[str]) -> list[dict]:
    findings: list[dict] = []
    legacy = [re.compile(r"https?://(www\.)?" + re.escape(re.sub(r"^www\.", "", h)) + r"\b[^\s\"'`)<>\\]*", re.I)
              for h in legacy_hosts]

    def add(kind, f, line_no, label, text):
        findings.append({"kind": kind, "file": str(f.relative_to(root)), "line": line_no,
                         "match": label, "text": text.strip()[:160]})

    for f in shipped_files(root):
        try:
            lines = f.read_text(encoding="utf-8", errors="replace").splitlines()
        except OSError:
            continue
        is_code = f.suffix.lower() in CODE_EXT
        for n, line in enumerate(lines, 1):
            if is_code and COMMENT.match(line):
                continue  # a code comment is not rendered copy
            for rx, label in PLACEHOLDER:
                m = rx.search(line)
                if m and not is_input_hint(line, m.start()):
                    add("placeholder", f, n, label, line)
                    break
            for rx, label in SCAFFOLD_TEXT:
                if rx.search(line):
                    add("scaffold", f, n, label, line)
            hit = next((m for m in (rx.search(line) for rx in legacy) if m), None)
            if hit:
                add("legacy-link", f, n, hit.group(0)[:80], line)
            elif WP_UPLOAD.search(line):
                add("legacy-link", f, n, "WordPress upload path", line)

    for rel in SCAFFOLD_FILES:
        if (root / rel).is_file():
            findings.append({"kind": "scaffold", "file": rel, "line": 0,
                             "match": "create-next-app starter asset", "text": "delete it if nothing references it"})
    for ico in (root / "app" / "favicon.ico", root / "src" / "app" / "favicon.ico"):
        if ico.is_file() and ico.stat().st_size == DEFAULT_FAVICON_BYTES:
            findings.append({"kind": "scaffold", "file": str(ico.relative_to(root)), "line": 0,
                             "match": "likely the default create-next-app favicon", "text": f"{DEFAULT_FAVICON_BYTES} bytes"})
    return findings


def main() -> int:
    ap = argparse.ArgumentParser(description="Find placeholder copy, scaffold leftovers and legacy-site links.")
    ap.add_argument("repo", nargs="?", default=".")
    ap.add_argument("--legacy-host", action="append", default=[], metavar="HOST",
                    help="host of the site being replaced (repeatable); absolute links to it are reported")
    ap.add_argument("--json", action="store_true", help="print findings as JSON")
    a = ap.parse_args()

    root = Path(a.repo).resolve()
    if not root.is_dir():
        ap.error(f"not a directory: {a.repo}")
    findings = scan(root, a.legacy_host)

    if a.json:
        print(json.dumps({"repo": str(root), "findings": findings}, indent=2))
    else:
        for kind in ("placeholder", "scaffold", "legacy-link"):
            hits = [x for x in findings if x["kind"] == kind]
            if hits:
                print(f"\n{kind} ({len(hits)})")
                for x in hits:
                    loc = f"{x['file']}:{x['line']}" if x["line"] else x["file"]
                    print(f"  {loc:<48} {x['match']:<34} {x['text']}")
        print(f"\n{len(findings)} finding(s) in {root}")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
